import { readFile, writeFile } from 'node:fs/promises';
import { buildApp } from '../src/app.js';
import { loadConfig } from '../src/config.js';
import type { Database } from '../src/database/index.js';

// Export offline. Never load .env, query PostgreSQL, or contact providers.
const config = loadConfig({ NODE_ENV: 'test', LOG_LEVEL: 'silent',
  DATABASE_URL: 'postgres://unused:unused@localhost/documentation',
  JWT_SECRET: 'offline-documentation-placeholder-secret-32-bytes' });
const database: Database = {
  async query() { throw new Error('Documentation export must not query the database'); },
  async session() { throw new Error('Documentation export must not query the database'); },
  async transaction() { throw new Error('Documentation export must not query the database'); },
  async close() {},
};
type Operation = { summary: string; description: string; security?: object[];
  parameters?: object[]; requestBody?: object; responses: Record<string, object> };
const app = buildApp(config, database);
try {
  const response = await app.inject('/docs/json');
  if (response.statusCode !== 200) throw new Error('OpenAPI export failed');
  const spec = response.json();
  const operations = Object.entries(spec.paths as Record<string, Record<string, Operation>>)
    .sort(([a], [b]) => a.localeCompare(b))
    .flatMap(([path, methods]) => Object.entries(methods).map(([method, operation]) => ({ path, method, operation })));
  const fence = (value: unknown) => '```json\n' + JSON.stringify(value, null, 2) + '\n```';
  const output = ['# PadiCheck API request and response reference', '',
    'Generated from registered Fastify routes by `npm.cmd run docs:export`. Do not edit this file by hand.', '',
    'Read [Frontend integration](frontend-integration.md) first for workflows, response record types, browser setup and unsupported features.', '',
    'Default base URL: `http://127.0.0.1:3000`. All paths below are relative to it. JSON bodies use `Content-Type: application/json`; media uses multipart FormData.', '',
    'Protected requests use `Authorization: Bearer <access_token>`. A security alternative `{}` means public access is also supported; Google challenge linking still requires JWT.', '',
    'Response schemas describe envelopes. Record properties marked `additionalProperties: true` are open objects; their fields are documented in the frontend guide. Optional envelope fields vary by operation.', '',
    'Standard API errors have `{ "error": { "code": "...", "message": "..." }, "request_id": "..." }`. `/ready` returning 503 instead uses `{ "status": "unavailable" }`. A 204 has no body.', '',
    `This snapshot contains **${operations.length} operations**. Runtime documentation: \`/docs/\`, \`/docs/json\`, \`/docs/yaml\`.`, '',
    '| Method | URL | Summary |', '| --- | --- | --- |',
    ...operations.map(({ path, method, operation }) => `| ${method.toUpperCase()} | \`${path}\` | ${operation.summary} |`), ''];
  for (const { path, method, operation } of operations) {
    output.push(`## ${method.toUpperCase()} ${path}`, '', operation.summary, '', operation.description, '',
      '**Security**', '', fence(operation.security ?? []), '');
    if (operation.parameters?.length) output.push('**Path and query parameters**', '', fence(operation.parameters), '');
    output.push('**Request body**', '', operation.requestBody ? fence(operation.requestBody) : 'No request body is required.', '');
    output.push('**Success responses**', '', fence(Object.fromEntries(Object.entries(operation.responses).filter(([status]) => status.startsWith('2')))), '');
    output.push('**Documented errors**', '', Object.entries(operation.responses).filter(([status]) => !status.startsWith('2'))
      .map(([status, value]) => `${status}: ${(value as { description?: string }).description}`).join('; '), '');
  }
  const files = [
    ['../docs/openapi.json', JSON.stringify(spec, null, 2) + '\n'],
    ['../docs/api-reference.md', output.join('\n')],
  ] as const;
  for (const [relative, content] of files) {
    const url = new URL(relative, import.meta.url);
    if (process.argv.includes('--check')) {
      if (await readFile(url, 'utf8') !== content) throw new Error(`Stale documentation: ${relative}; run npm.cmd run docs:export`);
    } else await writeFile(url, content);
  }
  process.stdout.write(JSON.stringify({ documentation: process.argv.includes('--check') ? 'current' : 'exported', operations: operations.length }) + '\n');
} finally { await app.close(); }
